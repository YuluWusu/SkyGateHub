/* ================================ VIEW DOI SOAT ========================== */
CREATE OR REPLACE VIEW `V_DON_DAT_TONG_HOP` AS
SELECT
  d.`MA_DON_DAT`,
  d.`MA_DON_HANG`,
  d.`TONG_TIEN` AS `TONG_TIEN_DANG_LUU`,
  COALESCE(ct.`TONG_CHI_TIET_HIEU_LUC`, 0) AS `TONG_CHI_TIET_HIEU_LUC`,
  COALESCE(tt.`DA_THU`, 0) AS `DA_THU`,
  COALESCE(ht.`DA_HOAN`, 0) AS `DA_HOAN`,
  COALESCE(tt.`DA_THU`, 0) - COALESCE(ht.`DA_HOAN`, 0) AS `DA_THU_RONG`,
  d.`TONG_TIEN` - (COALESCE(tt.`DA_THU`, 0) - COALESCE(ht.`DA_HOAN`, 0)) AS `CON_PHAI_THU_THEO_SO_DANG_LUU`,
  CASE
    WHEN COALESCE(ht.`DA_HOAN`, 0) > 0 AND COALESCE(tt.`DA_THU`, 0) - COALESCE(ht.`DA_HOAN`, 0) <= 0 THEN 'DA_HOAN_TIEN'
    WHEN COALESCE(tt.`DA_THU`, 0) - COALESCE(ht.`DA_HOAN`, 0) <= 0 THEN 'CHUA_THANH_TOAN'
    WHEN COALESCE(tt.`DA_THU`, 0) - COALESCE(ht.`DA_HOAN`, 0) >= d.`TONG_TIEN` THEN 'DA_THANH_TOAN'
    ELSE 'DA_DAT_COC'
  END AS `TRANG_THAI_THANH_TOAN_TINH`
FROM `DON_DAT` d
LEFT JOIN (
  SELECT `MA_DON_DAT`, SUM(`THANH_TIEN`) AS `TONG_CHI_TIET_HIEU_LUC`
  FROM `CHI_TIET_DON`
  WHERE `TRANG_THAI` = 'HIEU_LUC'
  GROUP BY `MA_DON_DAT`
) ct ON ct.`MA_DON_DAT` = d.`MA_DON_DAT`
LEFT JOIN (
  SELECT `MA_DON_DAT`, SUM(`SO_TIEN`) AS `DA_THU`
  FROM `THANH_TOAN`
  WHERE `TRANG_THAI` = 'DA_THANH_TOAN'
  GROUP BY `MA_DON_DAT`
) tt ON tt.`MA_DON_DAT` = d.`MA_DON_DAT`
LEFT JOIN (
  SELECT t.`MA_DON_DAT`, SUM(h.`SO_TIEN`) AS `DA_HOAN`
  FROM `HOAN_TIEN` h
  INNER JOIN `THANH_TOAN` t ON t.`MA_THANH_TOAN` = h.`MA_THANH_TOAN`
  WHERE h.`TRANG_THAI` = 'DA_HOAN'
  GROUP BY t.`MA_DON_DAT`
) ht ON ht.`MA_DON_DAT` = d.`MA_DON_DAT`;

