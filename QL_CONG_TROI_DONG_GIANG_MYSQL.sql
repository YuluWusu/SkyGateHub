-- 11. Bảng DON_DAT
CREATE TABLE `DON_DAT` (
  `MA_DON_DAT` INT NOT NULL AUTO_INCREMENT,
  `MA_DON_CODE` VARCHAR(30) NOT NULL UNIQUE,
