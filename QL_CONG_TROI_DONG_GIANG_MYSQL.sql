-- 14. Bảng DAT_VE (Sử dụng Generated Column STORED thay thế PERSISTED)
CREATE TABLE `DAT_VE` (
  `MA_DAT_VE` INT NOT NULL AUTO_INCREMENT,
  `MA_DON_DAT` INT NOT NULL,
  `MA_SAN_PHAM` INT NOT NULL,
  `NGAY_SU_DUNG` DATE NOT NULL,
  `SO_LUONG_NGUOI_LON` INT DEFAULT 0,
  `SO_LUONG_TRE_EM` INT DEFAULT 0,
  `DON_GIA_NGUOI_LON` DECIMAL(18, 2) NOT NULL,
  `DON_GIA_TRE_EM` DECIMAL(18, 2) NOT NULL,
  `THANH_TIEN` DECIMAL(18, 2) GENERATED ALWAYS AS (
    (COALESCE(`SO_LUONG_NGUOI_LON`, 0) * `DON_GIA_NGUOI_LON`) + 
    (COALESCE(`SO_LUONG_TRE_EM`, 0) * `DON_GIA_TRE_EM`)
  ) STORED,
  PRIMARY KEY (`MA_DAT_VE`),
  CONSTRAINT `FK_DATVE_DONDAT` FOREIGN KEY (`MA_DON_DAT`) REFERENCES `DON_DAT` (`MA_DON_DAT`) ON DELETE CASCADE,
  CONSTRAINT `FK_DATVE_SANPHAM` FOREIGN KEY (`MA_SAN_PHAM`) REFERENCES `SAN_PHAM_VE` (`MA_SAN_PHAM`),
  CONSTRAINT `CHK_DATVE_SOLUONG` CHECK ((`SO_LUONG_NGUOI_LON` + `SO_LUONG_TRE_EM`) > 0),
  CONSTRAINT `CHK_DATVE_SLNL` CHECK (`SO_LUONG_NGUOI_LON` >= 0),
  CONSTRAINT `CHK_DATVE_SLTE` CHECK (`SO_LUONG_TRE_EM` >= 0),
  CONSTRAINT `CHK_DATVE_DGNL` CHECK (`DON_GIA_NGUOI_LON` >= 0),
  CONSTRAINT `CHK_DATVE_DGTE` CHECK (`DON_GIA_TRE_EM` >= 0)
) ENGINE=InnoDB;

-- 15. Bảng DAT_AN (Sử dụng Generated Column STORED thay thế PERSISTED)
CREATE TABLE `DAT_AN` (
  `MA_DAT_AN` INT NOT NULL AUTO_INCREMENT,
  `MA_DON_DAT` INT NOT NULL,
  `MA_DICH_VU_AN` INT NOT NULL,
  `NGAY_DUNG_BUA` DATE NOT NULL,
  `CA_AN` VARCHAR(20) NOT NULL,
  `SO_SUAT` INT NOT NULL,
  `DON_GIA` DECIMAL(18, 2) NOT NULL,
  `MA_BAN` INT DEFAULT NULL,
  `THANH_TIEN` DECIMAL(18, 2) GENERATED ALWAYS AS (`SO_SUAT` * `DON_GIA`) STORED,
  `GHI_CHU` VARCHAR(200) DEFAULT NULL,
  PRIMARY KEY (`MA_DAT_AN`),
  CONSTRAINT `FK_DATAN_DONDAT` FOREIGN KEY (`MA_DON_DAT`) REFERENCES `DON_DAT` (`MA_DON_DAT`) ON DELETE CASCADE,
  CONSTRAINT `FK_DATAN_DICHVU` FOREIGN KEY (`MA_DICH_VU_AN`) REFERENCES `DICH_VU_AN` (`MA_DICH_VU_AN`),
  CONSTRAINT `FK_DATAN_BAN` FOREIGN KEY (`MA_BAN`) REFERENCES `BAN_AN` (`MA_BAN`),
  CONSTRAINT `CHK_DATAN_CAAN` CHECK (`CA_AN` IN ('TOI', 'TRUA', 'SANG')),
  CONSTRAINT `CHK_DATAN_SOSUAT` CHECK (`SO_SUAT` > 0),
  CONSTRAINT `CHK_DATAN_DONGIA` CHECK (`DON_GIA` >= 0)
) ENGINE=InnoDB;

