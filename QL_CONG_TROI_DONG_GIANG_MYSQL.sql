-- 1. Bảng VAI_TRO
CREATE TABLE `VAI_TRO` (
  `MA_VAI_TRO` INT NOT NULL AUTO_INCREMENT,
  `TEN_VAI_TRO` VARCHAR(50) NOT NULL UNIQUE,
  `MO_TA` VARCHAR(200) DEFAULT NULL,
  PRIMARY KEY (`MA_VAI_TRO`)
) ENGINE=InnoDB;

-- 2. Bảng NGUOI_DUNG
CREATE TABLE `NGUOI_DUNG` (
  `MA_NGUOI_DUNG` INT NOT NULL AUTO_INCREMENT,
  `TEN_DANG_NHAP` VARCHAR(50) NOT NULL UNIQUE,
  `MAT_KHAU` VARCHAR(255) NOT NULL,
  `HO_TEN` VARCHAR(100) NOT NULL,
  `SO_DIEN_THOAI` VARCHAR(15) NOT NULL,
  `EMAIL` VARCHAR(100) DEFAULT NULL,
  `TRANG_THAI` VARCHAR(20) DEFAULT 'HOAT_DONG',
  `NGAY_TAO` DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`MA_NGUOI_DUNG`),
  CONSTRAINT `CHK_NGUOIDUNG_TRANGTHAI` CHECK (`TRANG_THAI` IN ('KHOA', 'HOAT_DONG'))
) ENGINE=InnoDB;

-- 3. Bảng NGUOI_DUNG_VAI_TRO
CREATE TABLE `NGUOI_DUNG_VAI_TRO` (
  `MA_NGUOI_DUNG` INT NOT NULL,
  `MA_VAI_TRO` INT NOT NULL,
  PRIMARY KEY (`MA_NGUOI_DUNG`, `MA_VAI_TRO`),
  CONSTRAINT `FK_NDVT_NGUOIDUNG` FOREIGN KEY (`MA_NGUOI_DUNG`) REFERENCES `NGUOI_DUNG` (`MA_NGUOI_DUNG`) ON DELETE CASCADE,
  CONSTRAINT `FK_NDVT_VAITRO` FOREIGN KEY (`MA_VAI_TRO`) REFERENCES `VAI_TRO` (`MA_VAI_TRO`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. Bảng BAN_AN
CREATE TABLE `BAN_AN` (
  `MA_BAN` INT NOT NULL AUTO_INCREMENT,
  `SO_BAN` VARCHAR(20) NOT NULL UNIQUE,
  `SUC_CHUA` INT DEFAULT 4,
  `KHU_VUC` VARCHAR(50) DEFAULT 'NHA_HANG_CHINH',
  `TRANG_THAI` VARCHAR(30) DEFAULT 'SAN_SANG',
  PRIMARY KEY (`MA_BAN`),
  CONSTRAINT `CHK_BANAN_SUCCHUA` CHECK (`SUC_CHUA` > 0),
  CONSTRAINT `CHK_BANAN_TRANGTHAI` CHECK (`TRANG_THAI` IN ('BAO_TRI', 'DANG_DUNG', 'SAN_SANG'))
) ENGINE=InnoDB;

-- 5. Bảng LOAI_PHONG
CREATE TABLE `LOAI_PHONG` (
  `MA_LOAI_PHONG` INT NOT NULL AUTO_INCREMENT,
  `TEN_LOAI_PHONG` VARCHAR(100) NOT NULL UNIQUE,
  `SUC_CHUA_NGUOI_LON` INT DEFAULT 2,
  `GIA_CO_BAN` DECIMAL(18, 2) NOT NULL,
  `TY_LE_PHU_THU_CUOI_TUAN` DECIMAL(5, 2) DEFAULT 0.20,
  `MO_TA` VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (`MA_LOAI_PHONG`),
  CONSTRAINT `CHK_LOAIPHONG_GIACOBAN` CHECK (`GIA_CO_BAN` >= 0),
  CONSTRAINT `CHK_LOAIPHONG_SUCCHUA` CHECK (`SUC_CHUA_NGUOI_LON` > 0),
  CONSTRAINT `CHK_LOAIPHONG_TYLE` CHECK (`TY_LE_PHU_THU_CUOI_TUAN` >= 0)
) ENGINE=InnoDB;

-- 6. Bảng PHONG
CREATE TABLE `PHONG` (
  `MA_PHONG` INT NOT NULL AUTO_INCREMENT,
  `SO_PHONG` VARCHAR(20) NOT NULL UNIQUE,
  `MA_LOAI_PHONG` INT NOT NULL,
  `TANG` INT DEFAULT 1,
  `TRANG_THAI` VARCHAR(30) DEFAULT 'SAN_SANG',
  PRIMARY KEY (`MA_PHONG`),
  CONSTRAINT `FK_PHONG_LOAIPHONG` FOREIGN KEY (`MA_LOAI_PHONG`) REFERENCES `LOAI_PHONG` (`MA_LOAI_PHONG`),
  CONSTRAINT `CHK_PHONG_TRANGTHAI` CHECK (`TRANG_THAI` IN ('DANG_DON', 'BAO_TRI', 'DANG_O', 'SAN_SANG'))
) ENGINE=InnoDB;

-- 7. Bảng SAN_PHAM_VE
